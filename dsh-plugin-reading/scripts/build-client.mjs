#!/usr/bin/env node
/**
 * Concatenate the client halves in `client-src/` into the single browser bundle
 * `client.js` that `@deepseek-ai/dsh-client-modules` serves and the page's
 * module loader materialises.
 *
 * The parts share one factory closure: they are plain statements, not modules.
 * Order is the numeric filename prefix. A part may declare functions, consts
 * and call `addStyles(...)` at materialisation time; `99-apply.js` registers
 * the slot entries and returns the plugin object.
 */
import { promises as fs } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const manifest = JSON.parse(await fs.readFile(join(root, 'package.json'), 'utf8'))
const srcDir = join(root, 'client-src')

const names = (await fs.readdir(srcDir)).filter((name) => name.endsWith('.js')).sort()
const parts = []
for (const name of names) {
  const text = await fs.readFile(join(srcDir, name), 'utf8')
  parts.push(`// ---- client-src/${name} ----\n${text.trim()}\n`)
}

const banner = `/* Generated by scripts/build-client.mjs from client-src/*.js — do not edit directly. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory(require) {
`
const footer = `
  }
});
`
await fs.writeFile(join(root, 'client.js'), banner + parts.join('\n') + footer, 'utf8')
console.log(`built client.js from ${String(parts.length)} parts (${String((banner + parts.join('\n') + footer).length)} bytes)`)
